@api.route("/simulate/<int:org_id>", methods=["POST"])
def simulate_next_snapshot(org_id):
    """
    Generates a new, randomly-perturbed simulated signal snapshot for the
    organization based on its most recent one, then runs the full pipeline.
    This is a demo convenience -- in a real deployment this endpoint would
    be replaced by an ingestion feed of actual (simulated-in-this-project)
    telemetry connectors.
    """
    org = Organization.query.get_or_404(org_id)
    last_signal = (
        SecuritySignal.query.filter_by(org_id=org_id)
        .order_by(SecuritySignal.snapshot_date.desc())
        .first()
    )
    if not last_signal:
        return jsonify({"error": "No baseline signal to simulate from"}), 400

    scenario = request.get_json(silent=True) or {}
    direction = scenario.get("direction", "random")  # "worsen" | "improve" | "random"

    def drift(value, low, high, worsen_delta, improve_delta):
        if direction == "worsen":
            delta = worsen_delta
        elif direction == "improve":
            delta = improve_delta
        else:
            delta = random.choice([worsen_delta, improve_delta, 0])
        return max(low, min(high, value + delta))

    new_signal = SecuritySignal(
        org_id=org_id,
        snapshot_date=last_signal.snapshot_date + timedelta(days=30),
        critical_vulnerabilities=int(drift(last_signal.critical_vulnerabilities, 0, 25, random.randint(1, 4), -random.randint(0, 2))),
        patch_compliance_pct=drift(float(last_signal.patch_compliance_pct), 0, 100, -random.uniform(3, 10), random.uniform(1, 5)),
        mfa_coverage_pct=drift(float(last_signal.mfa_coverage_pct), 0, 100, -random.uniform(5, 15), random.uniform(1, 5)),
        security_incidents=int(drift(last_signal.security_incidents, 0, 20, random.randint(0, 2), -min(last_signal.security_incidents, random.randint(0, 1)))),
        backup_compliance_pct=drift(float(last_signal.backup_compliance_pct), 0, 100, -random.uniform(2, 10), random.uniform(1, 4)),
        endpoint_protection_pct=drift(float(last_signal.endpoint_protection_pct), 0, 100, -random.uniform(1, 5), random.uniform(1, 3)),
        training_compliance_pct=drift(float(last_signal.training_compliance_pct), 0, 100, -random.uniform(2, 8), random.uniform(1, 4)),
        avg_remediation_days=max(0, float(last_signal.avg_remediation_days) + (random.uniform(0.5, 3) if direction != "improve" else -random.uniform(0.2, 1.5))),
    )
    db.session.add(new_signal)
    db.session.flush()

    assessment = run_assessment_pipeline(org, new_signal)

    return jsonify({
        "signal": new_signal.to_dict(),
        "assessment": assessment.to_dict(),
    }), 201
