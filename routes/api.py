def _signal_to_score_input(signal: SecuritySignal) -> dict:
    return {
        "critical_vulnerabilities": signal.critical_vulnerabilities,
        "mfa_coverage_pct": float(signal.mfa_coverage_pct),
        "security_incidents": signal.security_incidents,
        "backup_compliance_pct": float(signal.backup_compliance_pct),
        "patch_compliance_pct": float(signal.patch_compliance_pct),
    }


def _latest_two_assessments(org_id):
    assessments = (
        RiskAssessment.query.filter_by(org_id=org_id)
        .order_by(RiskAssessment.assessment_date.desc())
        .limit(2)
        .all()
    )
    return assessments  # [current, previous] or [current] or []


def run_assessment_pipeline(org: Organization, signal: SecuritySignal):
    """
    Core orchestration: Signal -> Risk Score -> Explanation -> Exposure ->
    Gap Analysis -> (maybe) Alert. Used both by seeding and by the
    'simulate next snapshot' endpoint. Returns the created RiskAssessment.
    """
    score_input = _signal_to_score_input(signal)
    result = calculate_risk_score(score_input)

    assessment = RiskAssessment(
        org_id=org.org_id,
        signal_id=signal.signal_id,
        assessment_date=signal.snapshot_date,
        risk_score=result["risk_score"],
        risk_band=result["risk_band"],
        score_breakdown=result["breakdown"],
    )
    db.session.add(assessment)
    db.session.flush()  # get assessment_id without full commit

    # Find previous assessment (before this one) for explanation + alerting
    previous = (
        RiskAssessment.query.filter(
            RiskAssessment.org_id == org.org_id,
            RiskAssessment.assessment_date < signal.snapshot_date,
        )
        .order_by(RiskAssessment.assessment_date.desc())
        .first()
    )
    previous_score_dict = (
        {"risk_score": float(previous.risk_score), "breakdown": previous.score_breakdown}
        if previous else None
    )
    current_score_dict = {"risk_score": result["risk_score"], "breakdown": result["breakdown"], "risk_band": result["risk_band"]}
    explanation = explain_change(previous_score_dict, current_score_dict)

    # Financial exposure
    exposure_vals = estimate_exposure(org.to_dict(), score_input, result["risk_score"])
    exposure = FinancialExposure(
        org_id=org.org_id,
        assessment_id=assessment.assessment_id,
        ransomware_exposure=exposure_vals["ransomware_exposure"],
        data_breach_exposure=exposure_vals["data_breach_exposure"],
        business_interruption_exposure=exposure_vals["business_interruption_exposure"],
        incident_response_exposure=exposure_vals["incident_response_exposure"],
        regulatory_legal_exposure=exposure_vals["regulatory_legal_exposure"],
    )
    db.session.add(exposure)
    db.session.flush()

    # Coverage gap analysis (uses the org's active policy, if any)
    policy = Policy.query.filter_by(org_id=org.org_id, status="Active").first()
    coverage_list = [c.to_dict() for c in policy.coverages] if policy else []
    gaps = detect_gaps(exposure_vals, coverage_list)

    delta = explanation["delta"]
    if should_raise_alert(delta, gaps, current_app.config["RISK_INCREASE_ALERT_THRESHOLD"]):
        payload = build_alert_payload(explanation, gaps)
        alert = RiskAlert(
            org_id=org.org_id,
            assessment_id=assessment.assessment_id,
            exposure_id=exposure.exposure_id,
            previous_score=payload["previous_score"],
            current_score=payload["current_score"],
            main_reason=payload["main_reason"],
            coverage_gap_summary=payload["coverage_gap_summary"],
            recommendation=payload["recommendation"],
            status=payload["status"],
        )
        db.session.add(alert)
        db.session.flush()
        db.session.add(ReviewHistory(
            alert_id=alert.alert_id,
            action="Alert Generated",
            notes="Automatically generated by risk pipeline. Pending analyst review.",
        ))

    db.session.commit()
    return assessment


