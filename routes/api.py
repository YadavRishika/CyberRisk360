@api.route("/dashboard/<int:org_id>", methods=["GET"])
def dashboard(org_id):
    org = Organization.query.get_or_404(org_id)

    assessments = (
        RiskAssessment.query.filter_by(org_id=org_id)
        .order_by(RiskAssessment.assessment_date.asc())
        .all()
    )
    if not assessments:
        return jsonify({"error": "No assessments yet for this organization"}), 404

    current = assessments[-1]
    previous = assessments[-2] if len(assessments) > 1 else None

    current_dict = {"risk_score": float(current.risk_score), "breakdown": current.score_breakdown, "risk_band": current.risk_band}
    previous_dict = (
        {"risk_score": float(previous.risk_score), "breakdown": previous.score_breakdown}
        if previous else None
    )
    explanation = explain_change(previous_dict, current_dict)

    latest_signal = SecuritySignal.query.get(current.signal_id)
    exposure = (
        FinancialExposure.query.filter_by(assessment_id=current.assessment_id).first()
    )
    policy = Policy.query.filter_by(org_id=org_id, status="Active").first()
    coverage_list = [c.to_dict() for c in policy.coverages] if policy else []
    gaps = detect_gaps(exposure.to_dict(), coverage_list) if exposure else []

    alerts = RiskAlert.query.filter_by(org_id=org_id).order_by(RiskAlert.created_at.desc()).all()
    pending = [a for a in alerts if a.status == "Pending Analyst Review"]

    return jsonify({
        "organization": org.to_dict(),
        "trend": [{"date": a.assessment_date.isoformat(), "score": float(a.risk_score), "band": a.risk_band} for a in assessments],
        "current_assessment": current.to_dict(),
        "explanation": explanation,
        "latest_signal": latest_signal.to_dict() if latest_signal else None,
        "exposure": exposure.to_dict() if exposure else None,
        "policy": policy.to_dict() if policy else None,
        "coverage_gaps": gaps,
        "alerts": [a.to_dict() for a in alerts],
        "pending_review_count": len(pending),
        "disclaimer": current_app.config["DATA_DISCLAIMER"],
    })


