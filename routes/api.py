@api.route("/alerts/<int:alert_id>/review", methods=["POST"])
def review_alert(alert_id):
    """
    Human-in-the-loop decision endpoint. This is the ONLY way an alert's
    status changes. The system itself never auto-approves or auto-rejects.
    """
    alert = RiskAlert.query.get_or_404(alert_id)
    data = request.get_json(force=True) or {}

    analyst_name = data.get("analyst_name", "").strip()
    decision = data.get("decision")
    comments = data.get("comments", "")

    if not analyst_name:
        return jsonify({"error": "analyst_name is required"}), 400
    if decision not in ("Approve", "Reject", "Request Info"):
        return jsonify({"error": "decision must be Approve, Reject, or Request Info"}), 400

    review = AnalystReview(
        alert_id=alert_id,
        analyst_name=analyst_name,
        decision=decision,
        comments=comments,
    )
    db.session.add(review)

    status_map = {
        "Approve": "Approved",
        "Reject": "Rejected",
        "Request Info": "Info Requested",
    }
    alert.status = status_map[decision]

    db.session.add(ReviewHistory(
        alert_id=alert_id,
        action=f"Analyst decision: {decision}",
        notes=comments or "(no comments provided)",
    ))
    db.session.commit()

    return jsonify({
        "alert": alert.to_dict(),
        "review": review.to_dict(),
    })


